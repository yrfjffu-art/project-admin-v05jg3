export interface WorkflowOpts {
  name: string;
  task: string;
  module: string;
  jdk: string;
  sdk?: string | null;
  buildTools?: string | null;
  gradleVersion?: string | null;
  hasWrapper: boolean;
  root: string;
}

export function makeWorkflow(o: WorkflowOpts) {
  const wd = o.root.replace(/\/$/, '');
  const dirLine = wd ? `\n    defaults:\n      run:\n        working-directory: ${wd}` : '';
  const pkgs = [o.sdk ? `"platforms;android-${o.sdk}"` : '', o.buildTools ? `"build-tools;${o.buildTools}"` : ''].filter(Boolean).join(' ');
  const apkPath = `${wd ? wd + '/' : ''}${o.module ? o.module + '/' : ''}build/outputs/apk/**/*.apk`;
  const gradleCmd = o.hasWrapper ? './gradlew' : 'gradle';
  return `# Generated by APK Forge — builds ${o.name} on GitHub-hosted runners
name: Build APK (${o.name})

on:
  push:
    branches: [ main ]
  workflow_dispatch:

jobs:
  build:
    runs-on: ubuntu-latest${dirLine}
    steps:
      - uses: actions/checkout@v4

      - name: Set up JDK ${o.jdk}
        uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: '${o.jdk}'

      - name: Set up Android SDK
        uses: android-actions/setup-android@v3
${pkgs ? `
      - name: Install SDK packages
        run: sdkmanager ${pkgs}
` : ''}
      - name: Set up Gradle
        uses: gradle/actions/setup-gradle@v4${!o.hasWrapper && o.gradleVersion ? `\n        with:\n          gradle-version: '${o.gradleVersion}'` : ''}
${o.hasWrapper ? `
      - name: Make wrapper executable
        run: chmod +x gradlew
` : ''}
      - name: Build
        run: ${gradleCmd} ${o.task} --stacktrace

      - name: Upload APK
        uses: actions/upload-artifact@v4
        with:
          name: ${o.name.replace(/[^a-zA-Z0-9-_]/g, '-').toLowerCase()}-apk
          path: ${apkPath}
`;
}

export function taskFor(module: string, type: 'debug' | 'release') {
  const t = `assemble${type === 'debug' ? 'Debug' : 'Release'}`;
  const m = module.trim().replace(/\//g, ':');
  return m ? `:${m}:${t}` : t;
}

export function download(name: string, content: string, mime = 'text/yaml') {
  const blob = new Blob([content], { type: mime });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}
