// Single, static GitHub Actions workflow installed once in the user's build repo and started
// with workflow_dispatch. The server only triggers it and returns; the run reports back to
// POST /api/hooks/github with HMAC-signed callbacks (started / upload-url / finished / cancelled).
//
// Written with "%{" instead of "${" so the YAML and bash can be kept verbatim in a template
// literal; the placeholder is swapped back below.
export const FORGE_WORKFLOW_VERSION = 3;
export const FORGE_WORKFLOW_PATH = '.github/workflows/forge-build.yml';

export const ERROR_PATTERN = '^e: |^w: .*error|error:|Unresolved reference|Execution failed for task|What went wrong|AAPT|Manifest merger|Duplicate class|Could not resolve|Could not find|Cannot find symbol|compileSdk|minSdk';

const RAW = String.raw`# Managed by APK Forge / Web2APK - do not edit (forge-workflow-version: ${FORGE_WORKFLOW_VERSION})
name: APK Forge build
run-name: "Forge build #%{{ fromJSON(inputs.job).build_id }}"
on:
  workflow_dispatch:
    inputs:
      job:
        description: "Build job JSON (generated by APK Forge)"
        required: true
        type: string
permissions:
  contents: read
jobs:
  build:
    runs-on: ubuntu-24.04
    timeout-minutes: 45
    env:
      JOB: %{{ inputs.job }}
      PATTERN: '${ERROR_PATTERN}'
    steps:
      - name: Read job
        id: job
        run: |
          get() { jq -r --arg k "$1" '.[$k] // "" | tostring' <<< "$JOB" | tr -d '\r\n'; }
          CALLBACK_KEY="$(get callback_key)"
          SOURCE_URL="$(get source_url)"
          echo "::add-mask::$CALLBACK_KEY"
          echo "::add-mask::$SOURCE_URL"
          {
            echo "BUILD_ID=$(get build_id)"
            echo "SOURCE_URL=$SOURCE_URL"
            echo "TASK=$(get task)"
            echo "SDK_PLATFORM=$(get sdk_platform)"
            echo "BUILD_TOOLS=$(get build_tools)"
            echo "EXTRA_ARGS=$(get extra)"
            echo "CALLBACK_URL=$(get callback_url)"
            echo "CALLBACK_KEY=$CALLBACK_KEY"
          } >> "$GITHUB_ENV"
          cat > "$RUNNER_TEMP/forge-callback.sh" <<'EOF'
          #!/usr/bin/env bash
          # Reads a JSON payload on stdin, signs it and POSTs it to the Forge callback URL.
          set -euo pipefail
          [ -z "%{CALLBACK_URL:-}" ] && exit 0
          cat > "$RUNNER_TEMP/cb-payload.json"
          base64 -w0 "$RUNNER_TEMP/cb-payload.json" > "$RUNNER_TEMP/cb-p.txt"
          ts=$(date +%s)
          sig=$( { printf '%s.%s.' "$BUILD_ID" "$ts"; cat "$RUNNER_TEMP/cb-p.txt"; } | openssl dgst -sha256 -hmac "$CALLBACK_KEY" -r | cut -d' ' -f1)
          jq -n --argjson id "$BUILD_ID" --argjson ts "$ts" --rawfile p "$RUNNER_TEMP/cb-p.txt" --arg s "$sig" '{build_id:$id, ts:$ts, payload:$p, sig:$s}' > "$RUNNER_TEMP/cb-body.json"
          curl -fsS -m 60 --retry 3 --retry-all-errors -H 'Content-Type: application/json' --data-binary "@$RUNNER_TEMP/cb-body.json" "$CALLBACK_URL"
          EOF
          chmod +x "$RUNNER_TEMP/forge-callback.sh"
          echo "CB=$RUNNER_TEMP/forge-callback.sh" >> "$GITHUB_ENV"
      - name: Notify started
        continue-on-error: true
        run: |
          jq -nc --arg run_id "$GITHUB_RUN_ID" --arg run_url "$GITHUB_SERVER_URL/$GITHUB_REPOSITORY/actions/runs/$GITHUB_RUN_ID" '{event:"started", run_id:$run_id, run_url:$run_url}' | "$CB" > /dev/null
      - name: Set up JDK
        uses: actions/setup-java@v5
        with:
          distribution: temurin
          java-version: %{{ fromJSON(inputs.job).jdk }}
      - name: Set up Android SDK (preinstalled on runner)
        id: sdk
        run: |
          SDK="$ANDROID_HOME"
          [ -z "$SDK" ] && SDK="$ANDROID_SDK_ROOT"
          [ -z "$SDK" ] && SDK="/usr/local/lib/android/sdk"
          if [ ! -d "$SDK" ]; then echo "::error::Android SDK not found at $SDK"; exit 1; fi
          if [ -x "$SDK/cmdline-tools/latest/bin/sdkmanager" ]; then
            TOOLS_BIN="$SDK/cmdline-tools/latest/bin"
          else
            NEWEST=$(ls -1 "$SDK/cmdline-tools" 2>/dev/null | grep -v '^latest$' | sort -V | tail -1)
            if [ -z "$NEWEST" ] || [ ! -x "$SDK/cmdline-tools/$NEWEST/bin/sdkmanager" ]; then echo "::error::No sdkmanager found under $SDK/cmdline-tools"; exit 1; fi
            TOOLS_BIN="$SDK/cmdline-tools/$NEWEST/bin"
          fi
          echo "Using SDK: $SDK"
          echo "Using sdkmanager: $TOOLS_BIN/sdkmanager"
          echo "ANDROID_HOME=$SDK" >> "$GITHUB_ENV"
          echo "ANDROID_SDK_ROOT=$SDK" >> "$GITHUB_ENV"
          echo "SDKMANAGER=$TOOLS_BIN/sdkmanager" >> "$GITHUB_ENV"
          echo "$TOOLS_BIN" >> "$GITHUB_PATH"
          echo "$SDK/platform-tools" >> "$GITHUB_PATH"
      - name: Accept Android SDK licenses
        run: yes | "$SDKMANAGER" --licenses > /dev/null || true
      - name: Install SDK packages
        id: packages
        run: yes | "$SDKMANAGER" "platform-tools" "platforms;android-$SDK_PLATFORM" "build-tools;$BUILD_TOOLS"
      - name: Set up Gradle
        uses: gradle/actions/setup-gradle@v4
        with:
          gradle-version: %{{ fromJSON(inputs.job).gradle }}
      - name: Download and extract project
        id: extract
        run: |
          curl -fsSL --retry 3 -m 300 "$SOURCE_URL" -o source.zip
          mkdir -p src && unzip -q -o source.zip -d src
          ROOT=$(find src -maxdepth 6 \( -name settings.gradle -o -name settings.gradle.kts -o -name gradlew \) -not -path '*/__MACOSX/*' | awk '{ print gsub("/","/"), $0 }' | sort -n | head -1 | cut -d' ' -f2-)
          if [ -z "$ROOT" ]; then echo "::error::No settings.gradle / gradlew found in zip"; exit 1; fi
          echo "ROOT=$(dirname "$ROOT")" >> $GITHUB_ENV
          echo "Project root: $(dirname "$ROOT")"
      - name: Gradle build
        id: gradle
        run: |
          cd "$ROOT"
          echo "sdk.dir=$ANDROID_HOME" > local.properties
          if [ -f gradlew ]; then chmod +x gradlew; GRADLE=./gradlew; else GRADLE=gradle; fi
          $GRADLE "$TASK" --stacktrace --console=plain --warning-mode=none $EXTRA_ARGS 2>&1 | tee build.log
          STATUS=%{PIPESTATUS[0]}
          if [ "$STATUS" -ne 0 ]; then
            echo "===== FORGE: ERROR LINES ====="
            grep -nE "$PATTERN" build.log | head -80 || true
            echo "===== FORGE: WHAT WENT WRONG ====="
            sed -n '/^\* What went wrong:/,/^\* Try:/p' build.log
            echo "===== FORGE: END ====="
            exit "$STATUS"
          fi
      - name: Upload APK to Forge
        id: deliver
        run: |
          APK=$(find src -path '*/build/outputs/apk/*' -name '*.apk' -printf '%T@ %p\n' | sort -rn | head -1 | cut -d' ' -f2-)
          if [ -z "$APK" ]; then echo "::error::Gradle succeeded but no APK was found in */build/outputs/apk"; exit 1; fi
          NAME=$(basename "$APK"); SIZE=$(stat -c%s "$APK")
          echo "APK: $APK ($SIZE bytes)"
          if [ -z "$CALLBACK_URL" ]; then exit 0; fi
          RESP=$(jq -nc --arg n "$NAME" '{event:"upload-url", apk_name:$n}' | "$CB")
          URL=$(jq -r '.signed_url' <<< "$RESP"); DEST=$(jq -r '.path' <<< "$RESP")
          echo "::add-mask::$URL"
          curl -fsS -m 300 --retry 2 -X PUT -H 'Content-Type: application/vnd.android.package-archive' -H 'x-upsert: true' --data-binary "@$APK" "$URL" > /dev/null
          jq -nc --arg p "$DEST" --argjson s "$SIZE" '{event:"finished", status:"success", apk_path:$p, apk_size:$s}' | "$CB" > /dev/null
      - name: Upload APK artifact (fallback)
        if: success()
        uses: actions/upload-artifact@v4
        with:
          name: apk
          path: src/**/build/outputs/apk/**/*.apk
          if-no-files-found: error
          retention-days: 3
      - name: Report failure
        if: failure()
        env:
          FAILED_STEP: %{{ steps.sdk.outcome == 'failure' && 'Set up Android SDK' || steps.packages.outcome == 'failure' && 'Install SDK packages' || steps.extract.outcome == 'failure' && 'Download and extract project' || steps.gradle.outcome == 'failure' && 'Gradle build' || steps.deliver.outcome == 'failure' && 'Upload APK to Forge' || 'Workflow setup' }}
        run: |
          LOG="%{ROOT:-.}/build.log"
          : > "$RUNNER_TEMP/err.txt"; : > "$RUNNER_TEMP/www.txt"; : > "$RUNNER_TEMP/tail.txt"
          if [ -f "$LOG" ]; then
            grep -nE "$PATTERN" "$LOG" | head -80 > "$RUNNER_TEMP/err.txt" || true
            sed -n '/^\* What went wrong:/,/^\* Try:/p' "$LOG" | head -60 > "$RUNNER_TEMP/www.txt" || true
            grep -v -E '^\s+at (org\.gradle|org\.jetbrains|java\.base|kotlin\.)' "$LOG" | tail -n 200 | tail -c 60000 > "$RUNNER_TEMP/tail.txt" || true
          fi
          jq -nc --arg step "$FAILED_STEP" --rawfile e "$RUNNER_TEMP/err.txt" --rawfile w "$RUNNER_TEMP/www.txt" --rawfile t "$RUNNER_TEMP/tail.txt" \
            '{event:"finished", status:"failed", failed_step:$step, error_lines:$e, what_went_wrong:$w, log_tail:$t}' | "$CB" > /dev/null || true
      - name: Report cancellation
        if: cancelled()
        run: jq -nc '{event:"cancelled"}' | "$CB" > /dev/null || true
`;

export const FORGE_WORKFLOW = RAW.replaceAll('%{', '${');
